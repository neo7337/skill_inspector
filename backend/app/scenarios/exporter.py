"""
Exporters for synthetic test scenarios (pytest, JSON, Markdown).
"""
from __future__ import annotations

import json

from app.scenarios.models import ScenarioSuite


def export_as_json(suite: ScenarioSuite, indent: int = 2) -> str:
    """Export suite as formatted JSON string."""
    return json.dumps(suite.model_dump(), indent=indent)


def export_as_pytest(suite: ScenarioSuite) -> str:
    """Generate an executable pytest test file for the scenario suite."""
    clean_name = suite.skill_name.replace("-", "_").lower()

    lines = [
        '"""',
        f'Automated Agent Skill Test Suite: {suite.skill_name}',
        'Generated by Skill Inspector Scenario Generator',
        f'Total Scenarios: {suite.total_scenarios}',
        '"""',
        "import pytest",
        "from typing import Any",
        "",
        "# Mock Runner fixture for agent execution",
        "@pytest.fixture",
        "def agent_runner():",
        "    class MockAgentRunner:",
        "        async def run_skill(self, prompt: str, mock_tools: list[dict[str, Any]]) -> dict[str, Any]:",
        "            # Replace with your actual agent / skill dispatch runtime",
        '            return {"status": "success", "steps_taken": 2, "output": "Mock agent response"}',
        "    return MockAgentRunner()",
        "",
    ]

    for scenario in suite.scenarios:
        func_name = f"test_{clean_name}_{scenario.id}_{scenario.category}"
        mock_tools_json = json.dumps([m.model_dump() for m in scenario.mock_tools], indent=4)

        assertions_code = []
        for assertion in scenario.expected_assertions:
            assertions_code.append(
                f'    # Assert: {assertion}\n    assert result["status"] in ["success", "error", "graceful_exit"]'
            )
        assertions_block = "\n".join(assertions_code)

        lines.extend([
            "@pytest.mark.asyncio",
            f"async def {func_name}(agent_runner):",
            '    """',
            f'    Category: {scenario.category}',
            f'    Title: {scenario.title}',
            f'    Description: {scenario.description}',
            '    """',
            f'    prompt = {scenario.user_prompt!r}',
            f'    mock_tools = {mock_tools_json}',
            f'    max_steps = {scenario.max_step_budget}',
            '',
            '    result = await agent_runner.run_skill(prompt, mock_tools)',
            '',
            '    assert result["steps_taken"] <= max_steps, f"Step budget exceeded: {result[\'steps_taken\']} > {max_steps}"',
            f'{assertions_block}',
            "",
        ])

    return "\n".join(lines)


def export_as_markdown(suite: ScenarioSuite) -> str:
    """Generate a clean Markdown checklist for manual QA or review."""
    lines = [
        f"# Test Scenario Suite: `{suite.skill_name}`",
        "",
        f"**Total Scenarios:** {suite.total_scenarios} | **Breakdown:** " +
        ", ".join(f"{k}: {v}" for k, v in suite.categories_breakdown.items()),
        "",
        "---",
        "",
    ]

    for idx, s in enumerate(suite.scenarios, 1):
        lines.extend([
            f"### {idx}. [{s.category.upper()}] {s.title} (`{s.id}`)",
            "",
            f"**Description:** {s.description}",
            "",
            "**User Prompt:**",
            f"> {s.user_prompt}",
            "",
            f"**Max Step Budget:** {s.max_step_budget}",
            "",
            "**Expected Assertions:**",
        ])
        for a in s.expected_assertions:
            lines.append(f"- [ ] {a}")
        lines.append("")

    return "\n".join(lines)
